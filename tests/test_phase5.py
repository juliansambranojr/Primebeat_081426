class TestBriefDirect:
    """Test generate_brief at the module level."""

    def test_contains_unit_id(self, tmp_path):
        make_unit(tmp_path, "0500", "test", title="Test unit title")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "0500" in text

    def test_contains_title(self, tmp_path):
        make_unit(tmp_path, "0500", "test", title="Test unit title")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "Test unit title" in text

    def test_contains_keys(self, tmp_path):
        vals = {"figures.ratio": "3.07", "figures.residual": "0.0184"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "figures.ratio" in text
        assert "figures.residual" in text

    def test_no_raw_numeric_values(self, tmp_path):
        """The brief carries keys, not values. No digit crosses the boundary."""
        vals = {"figures.ratio": "3.07", "figures.residual": "0.0184",
                "census.rows": "422"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals),
                  body="**Some numbers.** The ratio was 3.07.\n")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        # The values 3.07, 0.0184, 422 must NOT appear in the brief.
        # We check the keys section specifically -- unit ids like 0500
        # are allowed as identifiers, not as numeric values.
        lines = text.split("\n")
        # Find lines that are in the "keys" section and contain values
        for val in ["3.07", "0.0184", "422"]:
            # The value should not appear anywhere in the brief
            assert val not in text, \
                f"value {val!r} leaked into the brief"

    def test_contains_type(self, tmp_path):
        make_unit(tmp_path, "0500", "test", type_="instrument-fix")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "instrument-fix" in text

    def test_contains_date(self, tmp_path):
        make_unit(tmp_path, "0500", "test")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "2026-09-03" in text

    def test_sealed_status(self, tmp_path):
        make_unit(tmp_path, "0500", "test", sealed=True)
        # Need to create a UNIT.sha256 for the sealed unit to be valid
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "sealed" in text.lower()

    def test_follows_chain(self, tmp_path):
        make_unit(tmp_path, "0500", "first")
        make_unit(tmp_path, "0501", "second", follows="0500")
        text = brief_mod.generate_brief("0501", cwd=tmp_path)
        assert "0500" in text

    def test_agents_listed(self, tmp_path):
        agents = [{"id": "abc123", "role": "build",
                    "block": "transcript/b01.md"}]
        make_unit(tmp_path, "0500", "test", agents=agents)
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "abc123" in text

    def test_paths_listed(self, tmp_path):
        make_unit(tmp_path, "0500", "test")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert "unit.md" in text

    def test_is_fenced_block(self, tmp_path):
        """Output should be a fenced block, easy to paste into a prompt."""
        make_unit(tmp_path, "0500", "test")
        text = brief_mod.generate_brief("0500", cwd=tmp_path)
        assert text.startswith("```")
        assert text.rstrip().endswith("```")


