# log(t/2) as a combination of log p, p prime: t -> (numerator factors, denominator factors)
LOGT = {
    F(49): ({7: 2}, {2: 1}),
    F(100): ({2: 1, 5: 2}, {}),
}
POINTS = [F(49), F(100)]
LOG_FROM = 20      # SignDataLog holds log m and (sqrt m)^-1 for m <= 19


def sig3(t):
    rho = F(1, 4)**2 + (t / 2)**2
    p = F(1, 4) / rho
    q = -(t / 2) / rho
    return F(1, 12) * q - F(1, 360) * (3 * p**2 * q - q**3)


def sig5(t):
    rho = F(1, 4)**2 + (t / 2)**2
    p = F(1, 4) / rho
    q = -(t / 2) / rho
    return (F(1, 12) * q - F(1, 360) * (3 * p**2 * q - q**3)
            + F(1, 1260) * (5 * p**4 * q - 10 * p**2 * q**3 + q**5)
            - F(1, 1680) * (7 * p**6 * q - 35 * p**4 * q**3 + 21 * p**2 * q**5 - q**7))


def gamma_phase5(t, logs):
    """`StirlingSeriesK5.gamma_phase_ball5`: Im logG(1/4 + it/2) in a ball."""
    l, el = logt_ball(t, logs)
    y = 1 / (2 * t)
    tau = y**6 / (1 - y) / 6
    expr = (t / 2) * (l + y**2 / 2 - y**4 / 4) - (PI0 / 2 + (-y + y**3 / 3 - y**5 / 5)) / 4 \
        - t / 2 + sig5(t)
    phi0 = rnd(expr)
    E = up(abs(expr - phi0) + (t / 2) * (el + tau) + (PIEPS / 2 + tau) / 4)
    Efin = up(E + F(10) / t**7)
    true = mp.im(mp.loggamma(mp.mpc(0.25, float(t) / 2)))
    check(abs(true - float(phi0)) <= float(Efin) + 1e-15, "gamma phase vs mpmath")
    print(f"t = {float(t):7.2f}  Im log Gamma(1/4 + it/2) = {float(phi0):.15f} +- {float(Efin):.2e}"
          f"  (Stirling part 10/t^7 = {float(F(10) / t**7):.1e}; mpmath {mp.nstr(true, 15)})")
    return phi0, E, Efin


