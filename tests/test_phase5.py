def make_unit(root, uid, slug, sealed=False, follows=None, body="",
              values_text=None, agents=None, refs=None, type_="run",
              title=None):
    """A loadable unit under `root/units/<uid>-<slug>/`."""
    path = root / "units" / f"{uid}-{slug}"
    (path / "run").mkdir(parents=True, exist_ok=True)
    fields = {"id": uid, "date": "2026-09-03", "type": type_,
              "title": title or slug, "refs": refs or [],
              "supersedes": [], "sealed": sealed}
    if follows is not None:
        fields = {**{k: v for k, v in fields.items() if k != "sealed"},
                  "follows": follows, "sealed": fields["sealed"]}
    if agents is not None:
        fields = {**{k: v for k, v in fields.items() if k != "sealed"},
                  "agents": agents, "sealed": fields["sealed"]}
    (path / "unit.md").write_text(
        "---\n" + unit_mod.format_front_matter(fields) + "\n---\n\n" + body,
        encoding="utf-8")
    if values_text is None:
        values_text = values_mod.EMPTY
    (path / "values.tsv").write_text(values_text, encoding="utf-8")
    return path


def _values_tsv(keys_values):
    """Build a values.tsv from a dict of {key: value}."""
    lines = [
        "# values.tsv -- GENERATED by `lab values` from run/. Do not edit.",
        "# source (none)",
    ]
    for k, v in keys_values.items():
        lines.append(f"{k}\t{v}")
    return "\n".join(lines) + "\n"


def _run_record_json(exit_code=0, wall_s=1.5):
    """A minimal lab_run JSON for testing."""
    import json
    return json.dumps({
        "schema_version": "v1.0",
        "unit": "units/0500-test",
        "runnable": "run/run.sh",
        "command": "/bin/sh -e run.sh",
        "argv": ["/bin/sh", "-e", "run.sh"],
        "cwd": "run",
        "exit_code": exit_code,
        "environment": {
            "lab_python": "v3.14.3",
            "os": "Darwin v25.6.0 arm64"
        },
        "meta": {
            "runnable_sha256": "abc123",
            "run_start": "2026-09-03T10:00:00Z",
            "run_end": "2026-09-03T10:00:01Z",
            "wall_s": wall_s
        }
    }, indent=2)


