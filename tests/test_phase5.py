class TestCiteDirect:
    """Test cite_value and cite_run at the module level."""

    def test_known_key(self, tmp_path):
        vals = {"figures.ratio": "3.07", "figures.residual": "0.0184"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        result = cite_mod.cite_value("0500", "figures.ratio",
                                     cwd=tmp_path)
        assert result == "3.07"

    def test_missing_key_raises(self, tmp_path):
        vals = {"figures.ratio": "3.07"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        with pytest.raises(cite_mod.CiteError) as exc_info:
            cite_mod.cite_value("0500", "no.such.key", cwd=tmp_path)
        # The error message should list available keys
        assert "figures.ratio" in str(exc_info.value)

    def test_bad_unit_raises(self, tmp_path):
        (tmp_path / "units").mkdir(parents=True, exist_ok=True)
        with pytest.raises(Exception):
            cite_mod.cite_value("9999", "x", cwd=tmp_path)


class TestCiteRun:
    """Test cite via the run() entrypoint (CLI-shaped)."""

    def test_prints_value_no_decoration(self, tmp_path):
        vals = {"ladder.ratio": "3.07", "ladder.rows": "422"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        code, out, err = _run(cite_mod.run, "0500", "ladder.ratio",
                              cwd=tmp_path)
        assert code == 0
        # Output is the value, a newline, and nothing else
        assert out == "3.07\n"

    def test_bad_key_exits_1(self, tmp_path):
        vals = {"ladder.ratio": "3.07"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        code, out, err = _run(cite_mod.run, "0500", "no.such",
                              cwd=tmp_path)
        assert code == 1
        # stderr lists available keys
        assert "ladder.ratio" in err

    def test_bad_unit_exits_2(self, tmp_path):
        (tmp_path / "units").mkdir(parents=True, exist_ok=True)
        code, out, err = _run(cite_mod.run, "9999", "x", cwd=tmp_path)
        assert code == 2

    def test_string_value(self, tmp_path):
        vals = {"inputs.formula": '"0.137 log T + 0.443"'}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        code, out, err = _run(cite_mod.run, "0500", "inputs.formula",
                              cwd=tmp_path)
        assert code == 0
        assert out == '"0.137 log T + 0.443"\n'

    def test_unit_prefix_resolution(self, tmp_path):
        vals = {"count": "42"}
        make_unit(tmp_path, "0500", "test",
                  values_text=_values_tsv(vals))
        code, out, err = _run(cite_mod.run, "0500", "count", cwd=tmp_path)
        assert code == 0
        assert out == "42\n"


