"""Phase 5 tests: `lab cite`, `lab brief`, `lab report`.

    python3 -m pytest tests/test_phase5.py -q

`lab cite <unit> <key>` prints a value from a unit's values.tsv so a
program or an agent can paste it without retyping. `lab brief <unit>`
generates a brief block that carries keys and unit ids -- no digits.
`lab report <unit>` generates a report block tagged with the unit id.

The design's § The agent interface:
    "A brief carries keys and unit ids. A report carries a generated
     block. No digit crosses either boundary as a keystroke. `lab cite`
     is how a value reaches prose; a model asking for a number gets it
     from the program."
"""

