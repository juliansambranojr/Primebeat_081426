"""Generator for the sign certificates through Stirling's series: `Stage3/StirlingSeriesLog.lean`
and `Stage3/StirlingSeriesPt*.lean`.  Block S14 of `lean_stage3/design/stencil.md`, Turing at scale.

The zeta side is `gen_signdata.py`'s (Euler-Maclaurin of order 4, the same balls, renamed
`s<t>_*`).  The Gamma side is `StirlingSeriesPhase.stirPhase3_ball`: one real ball for log(t/2),
the shared ball for log(pi), one closed-form ball for the phase phi_3(t) and one exponential ball,
whatever t is.  The old route (`SignDataGamma.re_lambda_eq`) needs n = 2^k >= t^2/6 factor balls.

Every rational is computed here with exact fractions, and every inequality a generated `norm_num`
closes is checked here first with the formula of the Lean lemma it feeds.  The phase is also
compared with mpmath's loggamma.

Usage:  python3 gen_stirlingseries.py [--write]   (from lean_stage3/checks/stirlingseries/)
"""
